const FALLBACK_PALETTES: Array<[string, string]> = [
  ['#1d4ed8', '#60a5fa'],
  ['#b91c1c', '#f87171'],
  ['#047857', '#34d399'],
  ['#b45309', '#fbbf24'],
  ['#6d28d9', '#a78bfa'],
  ['#0f766e', '#2dd4bf'],
  ['#be123c', '#fb7185'],
  ['#0369a1', '#38bdf8'],
  ['#4d7c0f', '#a3e635'],
  ['#c2410c', '#fb923c'],
  ['#4338ca', '#818cf8'],
  ['#a21caf', '#e879f9'],
];

export function getFallbackColors(seed: string): [string, string] {
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = (hash * 31 + seed.charCodeAt(i)) | 0;
  }
  const idx = Math.abs(hash) % FALLBACK_PALETTES.length;
  return FALLBACK_PALETTES[idx];
}

